function slug(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function stub(lemma, pack, d) {
  const base = lemma.toLowerCase();
  const collapsed = base.replace(/(.)\1/g, "$1");
  const wrong = [
    [collapsed === base ? base.slice(0, -1) : collapsed, "skipped_letter"],
    [`${base}e`, "extra_letter"],
    [base.replace(/[aeiou]/, "a"), "vowel_cluster"],
  ];
  return {
    id: slug(lemma),
    lemma,
    pack,
    d,
    wrong,
    tipEn: "Check the spelling carefully. British form preferred.",
    tipBn: "",
    reviewed: false,
  };
}

